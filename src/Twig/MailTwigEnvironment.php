<?php

declare(strict_types=1);

namespace Lle\HermesBundle\Twig;

use Twig\Environment;
use Twig\Error\SyntaxError;
use Twig\Extension\ExtensionInterface;
use Twig\Extension\SandboxExtension;
use Twig\Loader\ArrayLoader;
use Twig\RuntimeLoader\RuntimeLoaderInterface;
use Twig\Sandbox\SecurityError;
use Twig\Sandbox\SecurityPolicyInterface;

/**
 * Twig environment used to render mail templates (subject, sender name, html, text).
 *
 * Mail templates are written by users from the back office: they must not be compiled with the
 * application environment, which exposes its globals (`app.request`, environment variables…),
 * its template files (`include`, `source`) and every Twig function of the project.
 *
 * This environment only loads strings, has no global, never fails on an unknown variable and
 * only knows the extensions it is given. With a security policy, every template is sandboxed.
 * The runtime loader serves the extensions whose callables are runtime classes (Symfony's
 * `[FooRuntime::class, 'method']` pattern): the sandbox still decides which ones are callable.
 */
class MailTwigEnvironment extends Environment
{
    public const OPTIONS = [
        'strict_variables' => false,
        'autoescape' => 'html',
        'cache' => false,
    ];

    /** Generated by Twig in every sandboxed template. */
    public const SECURITY_CHECK_METHOD = 'checkSecurity';

    public const SECURITY_CHECK_MISSING = 'Sandboxed template "%s" has no security check: check the Twig version.';

    /**
     * @param iterable<ExtensionInterface> $extensions
     */
    public function __construct(
        iterable $extensions = [],
        ?SecurityPolicyInterface $securityPolicy = null,
        ?RuntimeLoaderInterface $runtimeLoader = null,
    ) {
        parent::__construct(new ArrayLoader(), self::OPTIONS);

        if ($runtimeLoader !== null) {
            $this->addRuntimeLoader($runtimeLoader);
        }

        foreach ($extensions as $extension) {
            $this->addExtension($extension);
        }

        if ($securityPolicy !== null) {
            $this->addExtension(new SandboxExtension($securityPolicy, true));
        }
    }

    /**
     * Compiles a template and, when sandboxed, checks every construct it uses — including those
     * of branches that would not run — without running it: no data needed, no side effect.
     *
     * @throws SyntaxError    invalid template, or unknown tag/filter/function
     * @throws SecurityError  construct refused by the sandbox
     */
    public function checkTemplate(string $template): void
    {
        $wrapper = $this->createTemplate($template);

        if ($this->hasExtension(SandboxExtension::class)) {
            // The sandbox only checks a template when it is displayed, from `checkSecurity()`
            // (generated in every sandboxed template). `unwrap()` is `@internal` in Twig: it is
            // the only way to reach that check without running the template, which would execute
            // its functions (SQL queries…) and fail for lack of data. Covered by the tests of
            // MailTwigEnvironmentTest, which break if Twig changes it.
            $compiled = $wrapper->unwrap();
            if (!method_exists($compiled, self::SECURITY_CHECK_METHOD)) {
                throw new \LogicException(sprintf(self::SECURITY_CHECK_MISSING, $compiled::class));
            }

            $compiled->checkSecurity();
        }
    }
}
